
# This file can now be deleted!
# It was used when setting up the package solution (using https://github.com/LottePitcher/opinionated-package-starter)

# set up git
git init
git branch -M main
git remote add origin https://github.com/GITHUB_USERNAME/GITHUB_REPOSITORY.git

# ensure latest Umbraco v18 templates used
dotnet new install Umbraco.Templates@18.* --force

# use the umbraco-extension dotnet template to add the package project
PACKAGE_NAME="PackageStarter"
cd src
dotnet new umbraco-extension -n "$PACKAGE_NAME" --site-domain "https://localhost:44300" --include-example

# replace package .csproj with the one from the template so has the extra information needed for publishing to nuget
cd PackageStarter
rm PackageStarter.csproj
mv PackageStarter_nuget.csproj PackageStarter.csproj

# remove the Directory.Packages.props generated by the umbraco-extension template - versions are managed centrally in src/Directory.Packages.props
rm Directory.Packages.props

# swap the generate-client script's hardcoded site URL for a per-worktree port looked up at
# generate time (via Umbraco.Community.WorktreeDevPort / worktree-dev-port), so it keeps working
# unchanged if you're ever running more than one worktree of this repo at once.
# Note: the umbraco-extension template's own generated generate-client script points at the
# wrong Swagger document name ("swagger" instead of the actual Constants.ApiName), so this
# derives the correct one itself (lowercased package name) rather than reusing that value.
mv ../../generate-openapi.js Client/scripts/generate-openapi.js
DOC_NAME=$(echo "$PACKAGE_NAME" | tr '[:upper:]' '[:lower:]')
npm pkg set scripts.generate-client="node scripts/generate-openapi.js $DOC_NAME" --prefix Client
npm pkg delete devDependencies.node-fetch --prefix Client
npm pkg set devDependencies.worktree-dev-port="^0.4.1" --prefix Client

# add project to solution
cd ..
dotnet sln add "PackageStarter"

# add reference to project from test site
dotnet add "PackageStarter.TestSite/PackageStarter.TestSite.csproj" reference "PackageStarter/PackageStarter.csproj"
